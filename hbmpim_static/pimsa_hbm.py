#!/usr/bin/env python3
"""PIMSA static analysis for HBM-PIM kernels (Samsung PIMSimulator PIMKernel).

Input: PIMSA-IR produced by the Clang frontend
    pim-analyzer --target=hbmpim --entry=PIMKernel::executeGemv ...
Output: per-PU (per pseudo-channel) metric vector, symbolic in the workload and
deployment parameters, plus the instantiated cost estimate of the paper's cost
model (Section "Cost Model"), specialized to HBM-PIM.

Two analyses over the same IR:

1. Symbolic metric extraction (paper, "Metric Extraction"): sequential
   composition sums, branches take the component-wise max unless the condition
   is decidable from the bindings, counted loops multiply by their symbolic
   trip count, and a loop over the PU set (pseudo-channels) is the PIMSA
   parallel region, so per-PU metrics are not scaled by it.

2. Row-activation estimation (paper, "Automatic Factor Estimation", row
   factor rho_row): abstract execution of the address stream of one PU at a
   concrete instantiation, through the architecture's address mapping
   (PIMAddrManager::addrGenSafe: column overflow carries into the row), with an
   open-page row-buffer state per bank. No data values, timing or simulator
   are involved.
"""
