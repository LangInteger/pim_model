class Ref:
    """An aggregate (object/pointer) named by an access path, e.g. w_data.bShape."""

    def __init__(self, name: str):
        self.name = name

    def __repr__(self):
        return f"Ref({self.name})"


class Opaque:
    def __init__(self, what: str):
        self.what = what

    def __repr__(self):
        return f"Opaque({self.what})"


@dataclass
class Addr:
    ch: int
    ra: int
    bg: int
    bank: int
    row: int
    col: int


class Break(Exception):
    pass


def classify(arch, write: bool, row):
    """Boundary class of a column command, from its row address alone.

    Rows with bit 13 set are reserved (PIMRank.h isReservedRA) and never reach
    the DRAM array. The PIM register row maps GRF/CRF/SRF and the control word
    (PIMRank::writeHab); the other reserved rows are bank parking (0x2000) and
    the all-bank mode registers (ABMR/SBMR). Every other row is a data row: in
    all-bank mode a column command to it moves one column between each of the
    P PIM blocks and its bank (Rank::sendToBank -> doPIM / readHab / writeHab).
    Returns None when the row is not a known integer.
    """
    if not isinstance(row, (int, sp.Integer)):
        return None
    pr = arch["M"]["pim_rows"]
    r = int(row)
    if r & (1 << pr["reserved_bit"]["value"]):
        if r == pr["register_row"]["value"]:
            return "host2pu" if write else "pu2host"
        return "mode_wr" if write else "mode_rd"
    return "pu2bank" if write else "bank2pu"


def is_true(v):
    if v is True or v is sp.true:
        return True
    if isinstance(v, (int, sp.Integer)) and not isinstance(v, bool):
        return int(v) != 0
    return False


def is_false(v):
    if v is False or v is sp.false:
        return True
    if isinstance(v, (int, sp.Integer)) and not isinstance(v, bool):
        return int(v) == 0
    return False


@dataclass
class Metrics:
    rd: sp.Expr = sp.Integer(0)  # column reads issued to this PU's channel
    wr: sp.Expr = sp.Integer(0)  # column writes issued to this PU's channel
    bar: sp.Expr = sp.Integer(0)  # barriers on this channel
    # The same column commands, by the architectural boundary their data crosses
    # (classify()). rd = bank2pu + pu2host + mode_rd, wr = pu2bank + host2pu + mode_wr.
    bank2pu: sp.Expr = sp.Integer(0)  # RD of a data row: bank -> PIM block (memory-register)
    pu2bank: sp.Expr = sp.Integer(0)  # WR of a data row: PIM block -> bank (register-memory)
    host2pu: sp.Expr = sp.Integer(0)  # WR of the PIM register row: host -> GRF/CRF/SRF/control
    pu2host: sp.Expr = sp.Integer(0)  # RD of the PIM register row: PIM registers -> host
    mode_rd: sp.Expr = sp.Integer(0)  # RD of another reserved row (bank parking): no payload
    mode_wr: sp.Expr = sp.Integer(0)  # WR of another reserved row (ABMR/SBMR mode switch)
    notes: list = field(default_factory=list)

    KEYS = ("rd", "wr", "bar", "bank2pu", "pu2bank", "host2pu", "pu2host", "mode_rd", "mode_wr")

    def __add__(self, o):
        return Metrics(*(getattr(self, k) + getattr(o, k) for k in self.KEYS),
                       notes=self.notes + o.notes)

    def scale(self, n):
        return Metrics(*(getattr(self, k) * n for k in self.KEYS), notes=self.notes)

    @staticmethod
    def max(a, b):
        return Metrics(*(sp.Max(getattr(a, k), getattr(b, k)) for k in Metrics.KEYS),
                       notes=a.notes + b.notes)

    def free_symbols(self):
        s = set()
        for k in self.KEYS:
            s |= sp.sympify(getattr(self, k)).free_symbols
        return s

    def subs(self, d):
        return Metrics(*(sp.simplify(sp.sympify(getattr(self, k)).subs(d)) for k in self.KEYS),
                       notes=self.notes)


class Interp:
    """Evaluator shared by the symbolic and concrete passes."""

    def __init__(self, arch: dict, bind: dict, chans, concrete: bool):
        self.arch = arch
        self.bind = dict(bind)
        self.concrete = concrete
        k = arch["kernel_constants"]
        self.globals = {kk: sp.Integer(v) for kk, v in k.items() if not kk.startswith("_")}
        self.globals["num_pim_chans_"] = chans
        self.globals["num_total_pim_blocks_"] = (
            self.globals["num_pim_blocks_"] * chans * self.globals["num_pim_ranks_"])
        self.globals["pim_chans_"] = Ref("pim_chans_")
        self.globals["pim_ranks_"] = Ref("pim_ranks_")
        self.cols_per_row = arch["M"]["burst_columns_per_row"]["value"]
        self.uid = 0
        # concrete-pass state: per-PU address stream split into barrier groups
        self.groups = [[]]
        self.cmds = []  # channel-0 column-command stream, in program order
        self.banks_per_bg = (arch["M"]["I2_banks"]["value"] // arch["M"]["bank_groups"]["value"])
        self.counts = {k: 0 for k in Metrics.KEYS}
        self.counts.update(w2r=0, r2w=0, data_outside_all_bank=0)
        self.last_dir = None
        self.all_bank = False  # concrete pass: rank 0 of channel 0 is in all-bank mode

    # -- expressions ---------------------------------------------------------
    def lookup(self, name, env):
        if name in env:
            return env[name]
        if name in self.globals:
            return self.globals[name]
        if name in self.bind:
            return sp.sympify(self.bind[name])
        return Ref(name)

    def path(self, base, suffix, env):
        if isinstance(base, Ref):
            key = base.name + suffix
            if key in self.bind:
                return sp.sympify(self.bind[key])
            return Ref(key)
        return Opaque(f"{base}{suffix}")

    def ev(self, e, env):
        if e is None:
            return Opaque("none")
        if "c" in e:
            v = e["c"]
            return sp.Integer(v) if isinstance(v, int) else sp.Float(v)
        if "str" in e:
            return e["str"]
        if "s" in e:
            return self.lookup(e["s"], env)
        if "mem" in e:
            return self.path(self.ev(e["base"], env), "." + e["mem"], env)
        if "idx" in e:
            i = self.ev(e["idx"], env)
            return self.path(self.ev(e["base"], env), f"[{i}]", env)
        if "fn" in e:
            return self.call_value(e, env)
        if "opaque" in e:
            return Opaque(e["opaque"])
        op = e["op"]
        a = self.ev(e.get("a"), env) if "a" in e else None
        if op == "real":
            return a
        if op == "neg":
            return -a
        if op == "!":
            return self.bool_not(a)
        b = self.ev(e["b"], env) if "b" in e else None
        if op == "?:":
            c = self.ev(e["c"], env)
            if is_true(c):
                return a
            if is_false(c):
                return b
            return sp.Piecewise((a, c), (b, True))
        if isinstance(a, (str, Opaque, Ref)) or isinstance(b, (str, Opaque, Ref)):
            if op in ("==", "!=") and isinstance(a, str) and isinstance(b, str):
                return sp.true if (a == b) == (op == "==") else sp.false
            return Opaque(f"{a}{op}{b}")
        if op == "+":
            return a + b
        if op == "-":
            return a - b
        if op == "*":
            return a * b
        if op == "/":
            return sp.floor(a / b) if e.get("int") else a / b
        if op == "%":
            return sp.Mod(a, b)
        if op == "<<":
            return a * 2 ** b
        if op == ">>":
            return sp.floor(a / 2 ** b)
        rel = {"<": sp.Lt, ">": sp.Gt, "<=": sp.Le, ">=": sp.Ge, "==": sp.Eq, "!=": sp.Ne}
        if op in rel:
            return rel[op](a, b)
        if op == "&&":
            return sp.And(self.as_bool(a), self.as_bool(b))
        if op == "||":
            return sp.Or(self.as_bool(a), self.as_bool(b))
        return Opaque(f"op {op}")

    @staticmethod
    def as_bool(v):
        if isinstance(v, (sp.Integer, int)) and not isinstance(v, bool):
            return sp.true if int(v) != 0 else sp.false
        return v

    def bool_not(self, v):
        v = self.as_bool(v)
        if isinstance(v, (Opaque, Ref, str)):
            return Opaque("!")
        return sp.Not(v)

    def call_value(self, e, env):
        fn = e["fn"]
        args = [self.ev(a, env) for a in e.get("args", [])]
        if fn == "ceil":
            return sp.ceiling(args[0])
        if fn == "floor":
            return sp.floor(args[0])
        if fn == "getPIMCmds":
            return Ref("getPIMCmds")
        if fn in ("size", "getTotalDim") and "obj" in e:
            obj = self.ev(e["obj"], env)
            return self.path(obj, "." + fn, env)
        if fn in ("addrGenSafe", "addrGen"):
            if not self.concrete:
                # Symbolic pass: keep the row/column expressions (no carry), which
                # is enough to classify the command by its row (classify()).
                return Addr(*args)
            ch, ra, bg, bank, row, col = (int(x) for x in args)
            if fn == "addrGenSafe":
                # PIMAddrManager::addrGenSafe(chan, rank, bg, bank, unsigned& row, unsigned& col)
                row += col // self.cols_per_row
                col %= self.cols_per_row
                for ref_arg, val in ((e["args"][4], row), (e["args"][5], col)):
                    if "s" in ref_arg:
                        self.assign_var(ref_arg["s"], sp.Integer(val), env)
            elif col >= self.cols_per_row:
                raise ValueError("addrGen with column overflow is not modeled")
            return Addr(ch, ra, bg, bank, row, col)
        return Opaque(fn)

    def assign_var(self, name, val, env):
        env[name] = val

    # -- statements -----------------------------------------------------------
    def run(self, nodes, env):
        m = Metrics()
        for n in nodes:
            m = m + self.stmt(n, env)
        return m

    def stmt(self, n, env):
        k = n["k"]
        if k == "let":
            env[n["var"]] = self.ev(n["val"], env) if "val" in n else Opaque("uninit")
            return Metrics()
        if k == "assign":
            var = n["var"]
            val = self.ev(n["val"], env)
            if n["op"] == "=":
                env[var] = val
            elif n["op"] in ("+=", "-=", "*=") and var in env and isinstance(env[var], sp.Basic) \
                    and isinstance(val, sp.Basic):
                cur = env[var]
                env[var] = cur + val if n["op"] == "+=" else cur - val if n["op"] == "-=" else cur * val
            else:
                env[var] = Opaque(f"assigned {var}")
            return Metrics()
        if k == "event":
            return self.event(n, env)
        if k == "call":
            callee = {}
            for p, a in zip(n["params"], n["args"]):
                callee[p] = self.ev(a, env)
            return self.run(n["body"], callee)
        if k == "opaque":
            return Metrics()
        if k == "if":
            c = self.as_bool(self.ev(n["cond"], env))
            if is_true(c):
                return self.run(n["then"], env)
            if is_false(c):
                return self.run(n["else"], env)
            if self.concrete:
                raise ValueError(f"undecidable branch in concrete pass: {n['cond']}")
            a, b = self.run(n["then"], dict(env)), self.run(n["else"], dict(env))
            m = Metrics.max(a, b)
            if any(sp.simplify(getattr(a, k) - getattr(b, k)) != 0 for k in Metrics.KEYS):
                m.notes.append(f"undecidable branch, component-wise max: {n['cond']}")
            return m
        if k == "break":
            raise Break()
        if k in ("for", "forrange", "while"):
            return self.loop(n, env)
        if k in ("continue", "return"):
            raise ValueError(f"'{k}' is not supported by the HBM pass")
        raise ValueError(f"unknown IR node {k}")

    def event(self, n, env):
        op = n["op"]
        args = n["args"]
        if op == "addBarrier":
            if self.concrete:
                if int(self.ev(args[0], env)) == 0:
                    self.counts["bar"] += 1
                    if self.groups[-1]:
                        self.groups.append([])
                    if self.cmds:
                        self.cmds[-1].bar = True
                return Metrics()
            return Metrics(bar=sp.Integer(1))
        if op == "addTransaction":
            w = self.as_bool(self.ev(args[0], env))
            if self.concrete:
                addr = self.ev(args[1], env)
                if not isinstance(addr, Addr):
                    raise ValueError(f"address not resolvable: {args[1]}")
                if addr.ch != 0:
                    return Metrics()
                write = is_true(w)
                self.counts["wr" if write else "rd"] += 1
                cls = classify(self.arch, write, addr.row)
                self.counts[cls] += 1
                pr = self.arch["M"]["pim_rows"]
                if write and addr.row == pr["abmr_row"]["value"]:
                    self.all_bank = True
                elif write and addr.row == pr["sbmr_row"]["value"]:
                    self.all_bank = False
                elif cls in ("bank2pu", "pu2bank") and not self.all_bank:
                    # A single-bank access to the array: analyze() rejects it, because
                    # the fan-out to all P PIM blocks used for V_mem needs all-bank mode.
                    self.counts["data_outside_all_bank"] += 1
                if self.last_dir is not None and self.last_dir != write:
                    self.counts["w2r" if self.last_dir else "r2w"] += 1
                self.last_dir = write
                self.groups[-1].append(((addr.ra, addr.bg, addr.bank), addr.row))
                self.cmds.append(ctl.Cmd(write, addr.ra, addr.bg * self.banks_per_bg + addr.bank,
                                         addr.row, addr.col))
                return Metrics()
            addr = self.ev(args[1], env)
            row = addr.row if isinstance(addr, Addr) else None
            dirs = [True] if is_true(w) else [False] if is_false(w) else [False, True]
            out = {}
            notes = [] if len(dirs) == 1 else ["unknown direction counted as read and write"]
            for write in dirs:
                out["wr" if write else "rd"] = sp.Integer(1)
                cls = classify(self.arch, write, row)
                if cls is None:
                    cls = "pu2bank" if write else "bank2pu"
                    notes.append(f"row not a known integer ({row}), counted as a data row")
                out[cls] = sp.Integer(1)
            return Metrics(**out, notes=notes)
        raise ValueError(f"unknown primitive {op}")

    # -- loops ------------------------------------------------------------------
    def is_pu_loop(self, n):
        """The PIMSA parallel region over the PU set (pseudo-channels)."""
        if n["k"] == "forrange":
            return n["range"].get("s") == "pim_chans_"
        if n["k"] == "for":
            c = n["cond"] or {}
            return c.get("op") == "<" and c.get("b", {}).get("s") == "num_pim_chans_"
        return False

    def loop(self, n, env):
        pu = self.is_pu_loop(n)
        if n["k"] == "forrange":
            rng = n["range"].get("s")
            var = n["var"]
            if pu:
                env[var] = sp.Integer(0) if self.concrete else sp.Symbol("pid", integer=True)
                return self.run(n["body"], env)
            if rng == "pim_ranks_":
                trip = self.globals["num_pim_ranks_"]
                if self.concrete:
                    m = Metrics()
                    for r in range(int(trip)):
                        env[var] = sp.Integer(r)
                        m = m + self.run(n["body"], env)
                    return m
                env[var] = sp.Symbol(var, integer=True, nonnegative=True)
                return self.run(n["body"], env).scale(trip)
            raise ValueError(f"range-for over {n['range']} not supported")

        if n["k"] == "while":
            raise ValueError("while loops are not supported by the HBM pass")

        # counted for-loop: init; var < hi | var <= hi; var += step
        for s in n["init"]:
            self.stmt(s, env)
        cond = n["cond"]
        inc = [s for s in n["inc"] if s["k"] == "assign"]
        if not cond or cond.get("op") not in ("<", "<=") or "s" not in cond["a"] or not inc:
            raise ValueError(f"unsupported loop form: {cond}")
        var = cond["a"]["s"]
        step_node = next((s for s in inc if s["var"] == var and s["op"] == "+="), None)
        if step_node is None:
            raise ValueError(f"loop variable {var} has no positive step")
        lo = env[var]

        if pu:
            env[var] = sp.Integer(0) if self.concrete else sp.Symbol("pid", integer=True)
            return self.run(n["body"], env)

        if self.concrete:
            m = Metrics()
            while is_true(self.as_bool(self.ev(cond, env))):
                try:
                    m = m + self.run(n["body"], env)
                except Break:
                    break
                for s in n["inc"]:
                    self.stmt(s, env)
            return m

        step = self.ev(step_node["val"], env)
        hi = self.ev(cond["b"], env)
        span = hi - lo + (1 if cond["op"] == "<=" else 0)
        trip = sp.Max(0, sp.ceiling(span / step))
        self.uid += 1
        t = sp.Symbol(f"t{self.uid}", integer=True, nonnegative=True)
        body_env = dict(env)
        body_env[var] = lo + step * t
        notes = []
        body = n["body"]
        # Leading `if (cond) break;` -> exact trip count when decidable.
        if body and body[0]["k"] == "if" and body[0]["then"] == [{"k": "break"}] \
                and not body[0]["else"]:
            trip, note = self.break_trip(body[0]["cond"], body_env, t, trip)
            notes.append(note)
            body = body[1:]
        try:
            m = self.run(body, body_env)
        except Break:
            raise ValueError("break inside loop body is only supported as a leading guard")
        # Variables (other than the induction variable) updated in the body
        # are unknown after the loop in the symbolic pass.
        for k2, v in body_env.items():
            if k2 != var and env.get(k2) is not v:
                env[k2] = Opaque(f"after-loop {k2}")
        env[var] = lo + step * trip
        if t in m.free_symbols():
            total = Metrics(*(sp.summation(getattr(m, kk), (t, 0, trip - 1)) for kk in Metrics.KEYS),
                            notes=m.notes)
        else:
            total = m.scale(trip)
        total.notes += notes
        return total

    def break_trip(self, cond_node, env, t, trip):
        c = self.ev(cond_node, env)
        if isinstance(trip, sp.Integer) and isinstance(c, sp.Basic) and c.free_symbols <= {t}:
            for i in range(int(trip)):
                if is_true(c.subs(t, i)):
                    return sp.Integer(i), f"break guard resolves trip count to {i}"
            return trip, "break guard never taken"
        return trip, "break guard undecidable: trip count is an upper bound"


def load_entry(ir_path: Path, entry: str):
    for e in json.loads(ir_path.read_text()):
        if e["entry"] == entry:
            return e
    raise SystemExit(f"entry {entry} not found in {ir_path}")


def entry_env(entry, kernel):
    env = {}
    for p in entry["params"]:
        if p in kernel["bind"]:
            env[p] = sp.sympify(kernel["bind"][p])
        else:
            env[p] = Ref(p)
    return env


def symbolic_metrics(ir_path, arch, kname):
    kern = KERNELS[kname]
    entry = load_entry(ir_path, kern["entry"])
    it = Interp(arch, kern["bind"], C, concrete=False)
    m = it.run(entry["body"], entry_env(entry, kern))
    return Metrics(*(sp.simplify(getattr(m, k)) for k in Metrics.KEYS), notes=sorted(set(m.notes)))


def concrete_stream(ir_path, arch, kname, values):
    """Abstract execution of one PU's command stream at a concrete instance."""
    kern = KERNELS[kname]
    entry = load_entry(ir_path, kern["entry"])
    bind = {k: sp.sympify(v).subs(values) for k, v in kern["bind"].items()}
    it = Interp(arch, bind, sp.Integer(values[C]), concrete=True)
    env = {p: (sp.sympify(bind[p]) if p in bind else Ref(p)) for p in entry["params"]}
    it.run(entry["body"], env)
    return it


# ----------------------------------------------------------------------------
# Cost model, per PU = per pseudo-channel.
#
# HBM-PIM has no PU-side instruction stream to time: every PIM operation is
# triggered by an all-bank column command and paced by it, so Cost_compute is
# folded into the command stream and Cost_host is zero inside the timed region.
# Cost_memory and Cost_buffer are the issue time of the PU's DRAM command
# stream under the memory controller, evaluated by controller.schedule: every
# delay is a named timing parameter (arch timing_cycles, from the device ini)
# or a Configuration.h derived delay, and every issue rule cites the
# PIMSimulator line that enforces it. The result is reported both as a total
# and broken down by the constraint each command waited on.
#
# worst_case_additive() is the earlier additive bound, kept until the
# worst-case analysis is redone.
# ----------------------------------------------------------------------------
def timing(arch):
    return {k: v["value"] for k, v in arch["timing_cycles"].items()}


def estimate(arch, cmds):
    m = arch["M"]
    cycles, breakdown, counts = ctl.schedule(
        cmds, timing(arch), m["ranks_per_channel"]["value"], m["I2_banks"]["value"],
        m["I2_banks"]["value"] // m["bank_groups"]["value"], m["command_queue_depth"]["value"])
    return {"total": cycles, "by_constraint": breakdown, "commands": counts}


def worst_case_additive(arch, rd, wr):
    """Every column command pays a full row cycle and a bus turnaround."""
    t = timing(arch)
    d = ctl.delays(t)
    ncol = rd + wr
    per = (max(d["READ_TO_PRE"], d["WRITE_TO_PRE"]) + t["tRP"] + max(t["tRCD_RD"], t["tRCD_WR"])
           + max(d["READ_TO_WRITE"], d["WRITE_TO_READ_B_LONG"]))
    base = ncol * per
    n_ref = -(-base // (t["tREFI"] // 2))  # a refresh every tREFI / NUM_RANKS, bounded above
    return {"total": base + n_ref * t["tRFC"], "per_command": per, "n_ref": n_ref}


# Constraint -> cost term of the paper's cost model. On HBM-PIM the terms are
# not added up: each is the time the command stream waited on those
# constraints in one evaluation (controller.schedule), so they partition it.
#   column     ~ V_mem / BW   (steady column-to-column spacing)
#   row        ~ N_mem * t_mem * rho_row   (opening/closing rows)
#   refresh, turnaround, issue: constraints the paper's formula has no term for
#   drain: read data return after the last command (tCMD + RL + BL/2) + 1
COST_TERMS = {
    "column": ("tCCD_L", "tCCD_S"),
    "row": ("tRCD_RD", "tRCD_WR", "tRP", "tRAS", "tRC", "tRTP", "tWR", "tRRD_L", "tRRD_S"),
    "refresh": ("tRFC",),
    "turnaround": ("R2W", "W2R", "tRTRS", "W2R_rank"),
    "issue": ("tCMD", "order"),
}


def cost_terms(by_constraint: dict, total: int) -> dict:
    known = {c for cs in COST_TERMS.values() for c in cs}
    unknown = set(by_constraint) - known
    if unknown:
        raise AssertionError(f"constraints without a cost term: {unknown}")
    out = {t: sum(by_constraint.get(c, 0) for c in cs) for t, cs in COST_TERMS.items()}
    out["drain"] = total - sum(out.values())
    return out


def metric_vector(arch, m: dict, act: int) -> dict:
    """The paper's per-PU metric vector, instantiated for HBM-PIM.

    Every column command moves BL * bus width = 32 B. A data-row command in
    all-bank mode does so between each of the P PIM blocks and its bank, inside
    the die, so V_mem counts P * 32 B per command while the channel bus carries
    one command. C_step equals N_mem: the PIM blocks take one step per such
    command (command-triggered execution), so compute adds no separate term.
    """
    col = arch["M"]["bytes_per_column_access"]["value"]
    p = arch["P"]["P_per_channel"]["value"]
    n_mem = m["bank2pu"] + m["pu2bank"]
    n_host = m["host2pu"] + m["pu2host"]
    n_col = m["rd"] + m["wr"]
    return {
        "N_host": n_host, "V_host_bytes": col * n_host,  # host <-> PIM registers, over the bus
        "N_mem": n_mem, "V_mem_bytes": p * col * n_mem,  # bank <-> PIM blocks, inside the die
        "internal_bytes_per_command": p * col, "bus_bytes_per_command": col,
        "C_step": n_mem,
        "N_mode": m["mode_rd"] + m["mode_wr"],  # parking and mode switches: no payload
        "N_bar": m["bar"],
        "N_col": n_col, "N_act": act, "rho_row": act / n_col,
    }


def analyze(ir_path, arch, kname, values):
    sym = symbolic_metrics(ir_path, arch, kname)
    inst = sym.subs(values)
    it = concrete_stream(ir_path, arch, kname, values)
    m = {k: int(getattr(inst, k)) for k in Metrics.KEYS}
    conc = {k: it.counts[k] for k in Metrics.KEYS}
    if m != conc:
        raise AssertionError(f"symbolic {m} != abstract execution {conc}")
    if it.counts["data_outside_all_bank"]:
        raise AssertionError(f"{it.counts['data_outside_all_bank']} data-row commands outside "
                             "all-bank mode: V_mem's fan-out to all PIM blocks does not hold")
    est = estimate(arch, it.cmds)
    est["by_term"] = cost_terms(est["by_constraint"], est["total"])
    act = est["commands"]["ACT"]
    return {
        "kernel": kname,
        "values": {str(k): int(v) for k, v in values.items()},
        "symbolic": {k: str(getattr(sym, k)) for k in Metrics.KEYS},
        "notes": sym.notes,
        "metrics": {**m, "act": act, "rho_row": act / (m["rd"] + m["wr"])},
        "metric_vector": metric_vector(arch, m, act),
        "worst_case": worst_case_additive(arch, m["rd"], m["wr"]),
        "estimate": est,
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ir", type=Path, required=True)
    ap.add_argument("--arch", type=Path, default=HERE / "arch" / "hbm2_pim.json")
    ap.add_argument("--kernel", choices=sorted(KERNELS), default="GEMV")
    ap.add_argument("--M", type=int, default=4096)
    ap.add_argument("--N", type=int, default=4096)
    ap.add_argument("--L", type=int, default=1048576)
    ap.add_argument("--B", type=int, default=1)
    ap.add_argument("--C", type=int, default=64)
    a = ap.parse_args(argv)
    arch = json.loads(a.arch.read_text())
    vals = {M: a.M, N: a.N, L: a.L, BT: a.B, C: a.C}
    keep = set(KERNELS[a.kernel]["params"].values()) | {C}
    vals = {k: v for k, v in vals.items() if k in keep}
    json.dump(analyze(a.ir, arch, a.kernel, vals), sys.stdout, indent=2, default=str)
    print()


if __name__ == "__main__":
    main()
